#!/bin/sh
# Extracts all i18n() strings from the widget into template.pot,
# then merges any new/changed strings into every existing *.po file.
# Plasma 6 version: reads metadata.json instead of metadata.desktop.
#
# Usage:  sh translate/merge.sh
# Needs:  gettext  (sudo apt install gettext / sudo pacman -S gettext)

DIR="$(cd "$(dirname "$0")" && pwd)"
PKGDIR="$(dirname "$DIR")"

plasmoidName=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["KPlugin"]["Id"])' "$PKGDIR/metadata.json")
widgetName="${plasmoidName##*.}"          # strip namespace -> rssreader
bugAddress=$(python3 -c 'import json,sys; d=json.load(open(sys.argv[1]))["KPlugin"]; print((d.get("Authors") or [{}])[0].get("Email") or d.get("Website", ""))' "$PKGDIR/metadata.json")
projectName="plasma_applet_${plasmoidName}"

if [ -z "$plasmoidName" ]; then
    echo "[merge] Error: could not read KPlugin.Id from metadata.json."
    exit 1
fi
echo "[merge] Domain: ${projectName}"

# --- 1. Pull the translatable metadata fields into a fake source file -------
# xgettext cannot read JSON, so we mirror Name/Description as i18n() calls.
python3 - "$PKGDIR/metadata.json" > "$DIR/metadata-strings.h" <<'PY'
import json, sys
k = json.load(open(sys.argv[1]))["KPlugin"]
def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"')
print('// Auto-generated by merge.sh -- do not edit, do not ship.')
print('// i18n: Widget name, shown in the "Add Widgets" browser and the KDE Store.')
print('i18nc("@title widget name", "%s");' % esc(k["Name"]))
print('// i18n: Short widget description, shown under the name in the widget browser.')
print('i18nc("@info widget description", "%s");' % esc(k["Description"]))
PY

# --- 2. Extract everything -------------------------------------------------
echo "[merge] Extracting messages"
cd "$PKGDIR" || exit 1
{
    find contents -name '*.qml' -o -name '*.js' | sort
    echo "translate/metadata-strings.h"
} > "$DIR/infiles.list"

xgettext \
    --files-from="$DIR/infiles.list" \
    --from-code=UTF-8 \
    --width=400 \
    --add-location=file \
    -C -kde -ci18n -ki18n:1 -ki18nc:1c,2 -ki18np:1,2 -ki18ncp:1c,2,3 \
    -ki18nd:2 -ki18ndc:2c,3 -kI18N_NOOP:1 -kI18N_NOOP2:1c,2 -kN_:1 \
    -D "$PKGDIR" \
    --package-name="${widgetName}" \
    --msgid-bugs-address="${bugAddress}" \
    -o "$DIR/template.pot.new" \
    || { echo "[merge] xgettext failed, aborting."; exit 1; }

sed -i 's|"Content-Type: text/plain; charset=CHARSET\\n"|"Content-Type: text/plain; charset=UTF-8\\n"|' "$DIR/template.pot.new"
sed -i 's|# SOME DESCRIPTIVE TITLE.|# Translation of '"${widgetName}"' in LANGUAGE|' "$DIR/template.pot.new"
sed -i "s|# Copyright (C) YEAR THE PACKAGE'S COPYRIGHT HOLDER|# Copyright (C) $(date +%Y)|" "$DIR/template.pot.new"

# Keep the old POT-Creation-Date if nothing else changed, so git stays quiet.
if [ -f "$DIR/template.pot" ]; then
    newDate=$(grep "POT-Creation-Date:" "$DIR/template.pot.new")
    oldDate=$(grep "POT-Creation-Date:" "$DIR/template.pot")
    sed -i "s|${newDate}|${oldDate}|" "$DIR/template.pot.new"
    if diff -q "$DIR/template.pot" "$DIR/template.pot.new" >/dev/null; then
        rm "$DIR/template.pot.new"
        echo "[merge] No string changes."
    else
        sed -i "s|${oldDate}|${newDate}|" "$DIR/template.pot.new"
        diff "$DIR/template.pot" "$DIR/template.pot.new" | grep "^>.*msgid" | cut -c 9- | sed 's/^/[merge]   + /'
        diff "$DIR/template.pot" "$DIR/template.pot.new" | grep "^<.*msgid" | cut -c 9- | sed 's/^/[merge]   - /'
        mv "$DIR/template.pot.new" "$DIR/template.pot"
    fi
else
    mv "$DIR/template.pot.new" "$DIR/template.pot"
fi

# --- 3. Merge into every existing translation ------------------------------
for cat in "$DIR"/*.po; do
    [ -e "$cat" ] || continue
    catLocale=$(basename "${cat%.*}")
    echo "[merge] Updating ${catLocale}.po"
    msgmerge --width=400 --add-location=file --no-fuzzy-matching \
        -o "$cat.new" "$cat" "$DIR/template.pot"
    sed -i 's|# Translation of '"${widgetName}"' in LANGUAGE|# Translation of '"${widgetName}"' in '"${catLocale}"'|' "$cat.new"
    mv "$cat.new" "$cat"
done

rm -f "$DIR/infiles.list"
echo "[merge] Done."
